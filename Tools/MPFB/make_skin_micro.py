"""T_Teen_SkinMicro_N: a tileable 512 px skin micro-normal (pores, fine creases), generated here, so CC0 (ours).
  python Tools/MPFB/make_skin_micro.py  -> P:/FoA-Assets/character/skin/T_Teen_SkinMicro_N.png (+ SOURCES.txt line)
Height = sparse pore dimples + two octaves of wrapped value noise + faint crossing creases; normal by wrapped
central differences. Tiled on the skin UVs (MicroTiles) and faded by MicroNormal in M_FoA_TeenSurface."""
import numpy as np
from PIL import Image

N = 512
rng = np.random.default_rng(1707)
yy, xx = np.mgrid[0:N, 0:N].astype(np.float32)


def wrapped_noise(cells):
    g = rng.random((cells, cells)).astype(np.float32)
    u, v = xx / N * cells, yy / N * cells
    i, j = np.floor(u).astype(int), np.floor(v).astype(int)
    fu, fv = u - i, v - j
    fu, fv = fu * fu * (3 - 2 * fu), fv * fv * (3 - 2 * fv)
    a, b = g[j % cells, i % cells], g[j % cells, (i + 1) % cells]
    c, d = g[(j + 1) % cells, i % cells], g[(j + 1) % cells, (i + 1) % cells]
    return (a * (1 - fu) + b * fu) * (1 - fv) + (c * (1 - fu) + d * fu) * fv


h = 0.35 * wrapped_noise(32) + 0.2 * wrapped_noise(96)
pores = np.zeros((N, N), np.float32)
for _ in range(2600):  # pores: small round dimples of uneven size and depth
    cx, cy, r, dep = rng.random() * N, rng.random() * N, rng.uniform(1.2, 2.6), rng.uniform(0.4, 1.0)
    dx = (xx - cx + N / 2) % N - N / 2
    dy = (yy - cy + N / 2) % N - N / 2
    m = np.abs(dx) < 4 * r
    m &= np.abs(dy) < 4 * r
    pores[m] -= dep * np.exp(-(dx[m] ** 2 + dy[m] ** 2) / (2 * r * r))
h += 0.55 * pores
for a, b in ((8, 3), (-2, 9)):  # faint crossing creases; integer frequencies keep the tile seamless
    t = (xx * a + yy * b) / N * 2 * np.pi
    h += 0.04 * np.sin(t + 3 * wrapped_noise(8))
h = (h - h.mean()) / h.std()
k = 1.6  # slope strength
gx = (np.roll(h, -1, 1) - np.roll(h, 1, 1)) * 0.5 * k
gy = (np.roll(h, -1, 0) - np.roll(h, 1, 0)) * 0.5 * k
n = np.stack([-gx, -gy, np.ones_like(h)], -1)
n /= np.linalg.norm(n, axis=-1, keepdims=True)
img = ((n * 0.5 + 0.5) * 255).round().astype(np.uint8)
out = 'P:/FoA-Assets/character/skin/T_Teen_SkinMicro_N.png'
Image.fromarray(img).save(out)
assert abs(float(n[..., 2].mean()) - 1) < 0.2, 'normal too strong'
with open('P:/FoA-Assets/character/skin/SOURCES.txt', 'w') as f:
    f.write('T_Teen_SkinMicro_N.png: generated by Tools/MPFB/make_skin_micro.py (procedural, seed 1707), CC0, no third-party data.\n')
print(out, 'mean z', float(n[..., 2].mean()))
