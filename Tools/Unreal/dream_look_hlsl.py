def common_hlsl():
    """Shared helpers, emitted at the top of each Custom node as static functions via a struct (Custom nodes can't
    declare free functions; a struct with static member functions is the standard workaround)."""
    return f"""
struct FDream
{{
    float Film(float x)
    {{{film_fn()}
    }}
    float Enc(float x) {{ x = max(x, 0.0); return x <= 0.0031308 ? x * 12.92 : 1.055 * pow(x, 1.0 / 2.4) - 0.055; }}
    float Lin(float x) {{ return x <= 0.04045 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4); }}
    float Curve(float yf, float4 cv)
    {{
        float tc = saturate((yf - cv.x) / (cv.y - cv.x));
        tc = tc + (tc * tc * (3.0 - 2.0 * tc) - tc) * cv.z;
        return pow(tc, cv.w);
    }}
}};
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    # a Custom node's code is one function body: close it, declare the helpers, reopen a dummy function (the classic
    # Custom-node helper trick), so the body below can call them
    helpers = "return 0;\n}\n" + common_hlsl() + "\nfloat DreamHelpersUnused()\n{\nreturn 0;"
    for name, body in (("INK", ink_hlsl()), ("LOOK", look_hlsl())):
        code = body.strip()
        open(f"{OUT}/{name}.hlsl", "w", encoding="utf-8").write(code)
        print(name, len(code), "chars")
    # the "Dream helpers" Custom node (float, wired into a dummy input of the main node so it compiles first)
    open(f"{OUT}/HELPERS.hlsl", "w", encoding="utf-8").write(helpers.strip())


if __name__ == "__main__":
    main()
