def film_fn():
    # constants of the curve, precomputed here exactly like lookdev.film()
    import math
    slope, toe, shoulder, black, white = 0.88, 0.62, 0.18, 0.0, 0.04
    ts, ss = 1 + black - toe, 1 + white - shoulder
    bt = (0.18 + black) / ts - 1
    tm = math.log10(0.18) - 0.5 * math.log((1 + bt) / (1 - bt)) * (ts / slope)
    st = (1 - toe) / slope - tm
    shm = shoulder / slope - st
    return f"""
float lc = log10(max(x, 1e-10));
float straight = {slope:g} * (lc + {st:.6f});
float toeC = lc < {tm:.6f} ? {-black:g} + {2 * ts:.6f} / (1.0 + exp({-2 * slope / ts:.6f} * (lc - {tm:.6f}))) : straight;
float shC = lc > {shm:.6f} ? {1 + white:g} - {2 * ss:.6f} / (1.0 + exp({2 * slope / ss:.6f} * (lc - {shm:.6f}))) : straight;
float tt = saturate((lc - {tm:.6f}) / {shm - tm:.6f});
{"tt = 1.0 - tt;" if shm < tm else ""}
tt = (3.0 - 2.0 * tt) * tt * tt;
return max(0.0, toeC + (shC - toeC) * tt);"""


