"""Rattle, masked silhouette decay and visible old-door wall. Called after base wardrobe graphs are built."""


def refine_wardrobe_scene():
    g,e=open_fn('PlayerTransition')
    pw=g.call(f'{GS}:GetPlayerPawn',256,224,PlayerIndex=0);cast=cast_to(g,'BP_FoAPlayer',544,0)
    apply=g.call(f'{cls_path(PLAYER)}:SetSandTransition',864,0)
    g.link(pw,'ReturnValue',cast,'Object');g.exec_chain(e,cast,apply);g.link(cast,'AsBP_FoAPlayer',apply,'self')
    g.link(e,'Amount',apply,'Amount');g.link(e,'Enable',apply,'Enable')
    g.comment('Real silhouette coverage','',g.ed.list_all_nodes(),C_VISUAL)

    g,e=open_fn('SetOldWall')
    wall=g.get('OldDoorWall',32,224);inv=g.call(f'{KML}:Not_PreBool',32,448)
    mesh=g.call('/Script/Engine.StaticMeshComponent:SetStaticMesh',-640,0,NewMesh='/Engine/BasicShapes/Cube.Cube')
    material=g.call('/Script/Engine.PrimitiveComponent:SetMaterial',-320,0,ElementIndex=0,
                    Material='/Game/FoA/Materials/MI_Wall_Plaster.MI_Wall_Plaster')
    g.link(wall,'OldDoorWall',mesh,'self');g.link(wall,'OldDoorWall',material,'self')
    hide=g.call(f'{SC}:SetHiddenInGame',320,0);vis=g.call(f'{SC}:SetVisibility',640,0)
    mode=g.branch(960,0);g.link(e,'Enable',mode,'Condition')
    collision=g.call('/Script/Engine.PrimitiveComponent:SetCollisionEnabled',1280,-160,NewType='QueryAndPhysics')
    clear=g.call('/Script/Engine.PrimitiveComponent:SetCollisionEnabled',1280,160,NewType='NoCollision')
    g.link(e,'Enable',inv,'A');g.link(inv,'ReturnValue',hide,'NewHidden')
    g.link(e,'Enable',vis,'bNewVisibility')
    for n in (hide,vis,collision,clear):g.link(wall,'OldDoorWall',n,'self')
    g.exec_chain(e,mesh,material,hide,vis,mode);g.link(mode,'True',collision,'execute');g.link(mode,'False',clear,'execute')
    g.comment('Close the old opening','',g.ed.list_all_nodes(),C_VISUAL)

    g,e=open_fn('WardrobeRattle')
    now=g.call(f'{GS}:GetTimeSeconds',32,224);start=g.get('WardrobeTransitionStart',32,448)
    elapsed=g.call(f'{KML}:Subtract_DoubleDouble',320,224);young=g.call(f'{KML}:Less_DoubleDouble',640,224,B=2.)
    gate=g.branch(960,0);g.link(now,'ReturnValue',elapsed,'A');g.link(start,'WardrobeTransitionStart',elapsed,'B')
    g.link(elapsed,'ReturnValue',young,'A');g.link(young,'ReturnValue',gate,'Condition');g.exec_chain(e,gate)
    phase=g.call(f'{KML}:Multiply_DoubleDouble',960,448,B=40.84);wave=g.call(f'{KML}:Sin',1280,448)
    strength=g.call(f'{KML}:Multiply_DoubleDouble',1600,448,B=1.25);rot=g.call(f'{KML}:MakeRotator',1920,448)
    home=g.get('WardrobePivotHome',1280,832);split=g.call(f'{KML}:BreakTransform',1600,832)
    compose=g.call(f'{KML}:ComposeRotators',2240,448)
    pivot=g.get('WardrobePivot',2240,832);apply=g.call(f'{SC}:K2_SetRelativeRotation',2560,0,bTeleport=True)
    g.link(elapsed,'ReturnValue',phase,'A');g.link(phase,'ReturnValue',wave,'A');g.link(wave,'ReturnValue',strength,'A')
    g.link(strength,'ReturnValue',rot,'Roll');g.link(home,'WardrobePivotHome',split,'InTransform')
    g.link(split,'Rotation',compose,'A');g.link(rot,'ReturnValue',compose,'B')
    g.link(compose,'ReturnValue',apply,'NewRotation');g.link(pivot,'WardrobePivot',apply,'self');g.link(gate,'True',apply,'execute')
    g.comment('Two seconds of rattle','',g.ed.list_all_nodes(),C_CAM)

    g=FGraph(DIR,'BeginWardrobeTransition')
    norm=lambda n:str(BEL.get_node_title(n)).replace(' ','').replace('\n','').lower()
    start=next(n for n in g.ed.list_nodes_of_class(unreal.K2Node_VariableSet) if norm(n)=='setwardrobetransitionstart')
    old=list(PIN.list_connected_pins(BEL.find_then_pin(start)));assert len(old)==1
    actor=g.get('Wardrobe',800,1280);cast=cast_to(g,'BP_Interactable',1120,1088)
    owner=g.set('WardrobeInteractor',1440,1088);pivot=g.get('Pivot',1440,1536,class_path='/Game/FoA/Gameplay/BP_Interactable.BP_Interactable_C')
    save_pivot=g.set('WardrobePivot',1760,1088);home=g.call(f'{SC}:GetRelativeTransform',1760,1536)
    save_home=g.set('WardrobePivotHome',2080,1088)
    duration=g.get('MoveTime',2080,1536,class_path='/Game/FoA/Gameplay/BP_Interactable.BP_Interactable_C')
    save_duration=g.set('WardrobeMoveTimeHome',2400,1088)
    slow=g.set('MoveTime',2720,1088,class_path='/Game/FoA/Gameplay/BP_Interactable.BP_Interactable_C');g.default(slow,'MoveTime',1.15)
    clear=g.set('WardrobeLastBurst',3040,1088)
    g.link(actor,'Wardrobe',cast,'Object');g.link(cast,'AsBP_Interactable',owner,'WardrobeInteractor')
    g.link(cast,'AsBP_Interactable',pivot,'self');g.link(pivot,'Pivot',save_pivot,'WardrobePivot')
    g.link(pivot,'Pivot',home,'self');g.link(home,'ReturnValue',save_home,'WardrobePivotHome')
    g.link(cast,'AsBP_Interactable',duration,'self');g.link(duration,'MoveTime',save_duration,'WardrobeMoveTimeHome')
    g.link(cast,'AsBP_Interactable',slow,'self');PIN.break_pin_links(BEL.find_then_pin(start))
    g.exec_chain(start,cast,owner,save_pivot,save_home,save_duration,slow,clear);con(BEL.find_then_pin(clear),old[0])
    g.comment('Cache the actual wardrobe','',[actor,cast,owner,pivot,save_pivot,home,save_home,duration,save_duration,slow,clear],C_DATA)

    g,e=open_fn('WardrobeSandTick')
    active,br=wardrobe_active(g,e);rattle=g.call(me('WardrobeRattle'),544,0);g.link(br,'True',rattle,'execute')
    now=g.call(f'{GS}:GetTimeSeconds',544,224);start=g.get('WardrobeTransitionStart',544,448)
    elapsed=g.call(f'{KML}:Subtract_DoubleDouble',864,224);impact=g.call(f'{KML}:GreaterEqual_DoubleDouble',1184,224,B=3.15)
    gate=g.branch(1504,0);g.link(now,'ReturnValue',elapsed,'A');g.link(start,'WardrobeTransitionStart',elapsed,'B')
    g.link(elapsed,'ReturnValue',impact,'A');g.link(impact,'ReturnValue',gate,'Condition');g.exec_chain(rattle,gate)
    after=g.call(f'{KML}:GreaterEqual_DoubleDouble',1824,448,B=6.1);settle=g.branch(2144,0)
    g.link(elapsed,'ReturnValue',after,'A');g.link(after,'ReturnValue',settle,'Condition');g.link(gate,'True',settle,'execute')
    out=g.call(f'{KML}:Subtract_DoubleDouble',1824,832,A=4.15);dout=g.call(f'{KML}:Divide_DoubleDouble',2144,832,B=1.)
    inside=g.call(f'{KML}:Subtract_DoubleDouble',1824,1056,B=5.05);din=g.call(f'{KML}:Divide_DoubleDouble',2144,1056,B=1.05)
    early=g.call(f'{KML}:Less_DoubleDouble',2144,1280,B=5.05);pick=g.call(f'{KML}:SelectFloat',2464,832)
    clamp=g.call(f'{KML}:FClamp',2784,832,Min=0.,Max=1.)
    transition=g.call(me('PlayerTransition'),3104,160,Enable=True)
    g.link(elapsed,'ReturnValue',out,'B');g.link(out,'ReturnValue',dout,'A')
    g.link(elapsed,'ReturnValue',inside,'A');g.link(inside,'ReturnValue',din,'A')
    g.link(elapsed,'ReturnValue',early,'A');g.link(early,'ReturnValue',pick,'bPickA')
    g.link(dout,'ReturnValue',pick,'A');g.link(din,'ReturnValue',pick,'B');g.link(pick,'ReturnValue',clamp,'Value')
    g.link(clamp,'ReturnValue',transition,'Amount');g.link(settle,'False',transition,'execute')
    restore=g.call(me('PlayerTransition'),2464,-192,Enable=False)
    remain=g.call(f'{KML}:Subtract_DoubleDouble',2784,-640,A=7.2);divide=g.call(f'{KML}:Divide_DoubleDouble',3104,-640,B=1.1)
    fade=g.call(f'{KML}:FClamp',3424,-640,Min=0.,Max=1.);skin=g.call(f'{KML}:Lerp',3744,-640,A=.06,B=1.)
    overlay=g.call(me('PlayerSand'),4064,-192)
    g.link(elapsed,'ReturnValue',remain,'B');g.link(remain,'ReturnValue',divide,'A');g.link(divide,'ReturnValue',fade,'Value')
    g.link(fade,'ReturnValue',skin,'Alpha');g.link(skin,'ReturnValue',overlay,'Amount');g.link(settle,'True',restore,'execute');g.exec_chain(restore,overlay)
    last=g.get('WardrobeLastBurst',3424,1280);delta=g.call(f'{KML}:Subtract_DoubleDouble',3744,1280)
    ready=g.call(f'{KML}:GreaterEqual_DoubleDouble',4064,1280,B=.35);visible=g.call(f'{KML}:Less_DoubleDouble',3744,1504,B=4.15)
    reform=g.call(f'{KML}:GreaterEqual_DoubleDouble',3744,1728,B=5.05);either=g.call(f'{KML}:BooleanOR',4064,1504)
    both=g.call(f'{KML}:BooleanAND',4384,1280);burst_gate=g.branch(4704,160)
    save=g.set('WardrobeLastBurst',5024,160);burst=g.call(me('WardrobeBodyBurst'),5344,160)
    g.link(elapsed,'ReturnValue',delta,'A');g.link(last,'WardrobeLastBurst',delta,'B');g.link(delta,'ReturnValue',ready,'A')
    g.link(elapsed,'ReturnValue',visible,'A');g.link(elapsed,'ReturnValue',reform,'A')
    g.link(visible,'ReturnValue',either,'A');g.link(reform,'ReturnValue',either,'B')
    g.link(ready,'ReturnValue',both,'A');g.link(either,'ReturnValue',both,'B');g.link(both,'ReturnValue',burst_gate,'Condition')
    g.exec_chain(transition,burst_gate);g.link(burst_gate,'True',save,'execute');g.link(elapsed,'ReturnValue',save,'WardrobeLastBurst');g.exec_chain(save,burst)
    g.comment('Scatter then re-form','',g.ed.list_all_nodes(),C_VISUAL)

    g=FGraph(DIR,'FinishWardrobeTransition');e=entry_node(g)
    old=list(PIN.list_connected_pins(BEL.find_then_pin(e)));assert len(old)==1
    restore=g.call(me('PlayerTransition'),-640,0,Enable=False)
    PIN.break_pin_links(BEL.find_then_pin(e));g.exec_chain(e,restore);con(BEL.find_then_pin(restore),old[0])
    off=next(n for n in g.ed.list_nodes_of_class(unreal.K2Node_VariableSet) if norm(n)=='setbwardrobetransition')
    old=list(PIN.list_connected_pins(BEL.find_then_pin(off)));assert len(old)==1
    actor=g.get('WardrobeInteractor',1824,1088);stop=g.call('/Game/FoA/Gameplay/BP_Interactable.BP_Interactable_C:StopPivotMotion',2144,896)
    clear=g.call(f'{KSL}:K2_ClearTimer',2464,896,FunctionName='WardrobeBeginFall')
    force=g.call('/Game/FoA/Gameplay/BP_Interactable.BP_Interactable_C:ApplyState',2784,896,NewState='Fallen',bInstant=True)
    duration=g.get('WardrobeMoveTimeHome',2784,1312);back=g.set('MoveTime',3104,896,class_path='/Game/FoA/Gameplay/BP_Interactable.BP_Interactable_C')
    for n in (stop,force,back):g.link(actor,'WardrobeInteractor',n,'self')
    g.link(actor,'WardrobeInteractor',clear,'Object');g.link(duration,'WardrobeMoveTimeHome',back,'MoveTime')
    PIN.break_pin_links(BEL.find_then_pin(off));g.exec_chain(off,stop,clear,force,back);con(BEL.find_then_pin(back),old[0])
    g.comment('Restore every interruption','',[restore,actor,stop,clear,force,duration,back],C_CAM)
