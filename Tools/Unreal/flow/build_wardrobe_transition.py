"""Director-owned wardrobe cinematic; loaded by build_director.py after its function declarations."""

VANISH_AT, REAPPEAR_AT, FINISH_AT = 4.15, 5.05, 7.2
TRANSITION_TIMERS = ('WardrobeSandTick', 'WardrobeVanish', 'WardrobeReappear', 'FinishWardrobeTransition')


def wardrobe_active(g, e):
    active = g.get('bWardrobeTransition', 32, 192)
    br = g.branch(288, 0)
    g.link(active, 'bWardrobeTransition', br, 'Condition'); g.exec_chain(e, br)
    return active, br


def wardrobe_pawn(g, x=544, y=192):
    pw = g.call(f'{GS}:GetPlayerCharacter', x, y, PlayerIndex=0)
    cm = g.get('CharacterMovement', x + 288, y, class_path='/Script/Engine.Character')
    g.link(pw, 'ReturnValue', cm, 'self')
    return pw, cm


def build_wardrobe_transition():
    assert 0 < VANISH_AT < REAPPEAR_AT < FINISH_AT

    g, e = open_fn('SetWardrobeEcho')
    enable = g.branch(256, 0); g.link(e, 'Enable', enable, 'Condition'); g.exec_chain(e, enable)
    dream = g.call(f'{GS}:GetActorOfClass', 544, -128, ActorClass=cls_path(DREAM))
    valid = g.call(f'{KSL}:IsValid', 544, 224); found = g.branch(832, -128)
    save_owner = g.set('WardrobeDream', 1120, -128)
    base = g.get('BaseEcho', 1120, 224, class_path=cls_path(DREAM)); save = g.set('WardrobeEchoHome', 1408, -128)
    calm = g.call(f'{cls_path(DREAM)}:SetEchoStrength', 1696, -128, Amount=0.03)
    g.link(enable, 'True', dream, 'execute'); g.exec_chain(dream, found)
    g.link(dream, 'ReturnValue', valid, 'Object'); g.link(valid, 'ReturnValue', found, 'Condition')
    g.link(dream, 'ReturnValue', save_owner, 'WardrobeDream'); g.link(dream, 'ReturnValue', base, 'self')
    g.link(base, 'BaseEcho', save, 'WardrobeEchoHome'); g.link(dream, 'ReturnValue', calm, 'self')
    g.link(found, 'True', save_owner, 'execute'); g.exec_chain(save_owner, save, calm)
    owner = g.get('WardrobeDream', 544, 736); home = g.get('WardrobeEchoHome', 1120, 736)
    owner_valid = g.call(f'{KSL}:IsValid', 832, 736); restore_ok = g.branch(832, 512)
    restore = g.call(f'{cls_path(DREAM)}:SetEchoStrength', 1408, 512)
    clear = g.set('WardrobeDream', 1696, 512)
    g.link(enable, 'False', restore_ok, 'execute'); g.link(owner, 'WardrobeDream', owner_valid, 'Object')
    g.link(owner_valid, 'ReturnValue', restore_ok, 'Condition'); g.link(owner, 'WardrobeDream', restore, 'self')
    g.link(home, 'WardrobeEchoHome', restore, 'Amount'); g.link(restore_ok, 'True', restore, 'execute')
    g.exec_chain(restore, clear)
    g.comment('Let the body read', '', [e, enable, dream, valid, found, save_owner, base, save, calm,
              owner, home, owner_valid, restore_ok, restore, clear], C_CAM)

    g, e = open_fn('SetWardrobeShot')
    light = g.get('WardrobeKeyLight', 32, -224)
    light_on = g.call(f'{SC}:SetVisibility', 256, -224)
    echo = g.call(me('SetWardrobeEcho'), 544, -224)
    branch = g.branch(256, 0); g.link(e, 'Enable', branch, 'Condition'); g.exec_chain(e, light_on, echo, branch)
    g.link(e, 'Enable', echo, 'Enable')
    g.link(light, 'WardrobeKeyLight', light_on, 'self'); g.link(e, 'Enable', light_on, 'bNewVisibility')
    camera = g.get('TopDownCamera', 256, 224)
    home = g.call(f'{SC}:GetRelativeTransform', 544, 224)
    fov = g.get('FieldOfView', 544, 384, class_path='/Script/Engine.CameraComponent')
    save_home = g.set('WardrobeCameraHome', 832, -128); save_fov = g.set('WardrobeCameraFOV', 1120, -128)
    # shortcut: framed for this wardrobe placement; reframe if the bedroom layout changes.
    location = g.call(f'{KML}:MakeVector', 1120, 224, X=-60.0, Y=-230.0, Z=255.0)
    rotation = g.call(f'{KML}:MakeRotator', 1120, 416, Pitch=-19.0, Yaw=47.0)
    pose = g.call(f'{KML}:MakeTransform', 1408, 224)
    close = g.call(f'{SC}:K2_SetRelativeTransform', 1696, -128, bTeleport='true')
    zoom = g.call('/Script/Engine.CameraComponent:SetFieldOfView', 1984, -128, InFieldOfView=60.0)
    g.link(camera, 'TopDownCamera', home, 'self'); g.link(camera, 'TopDownCamera', fov, 'self')
    g.link(home, 'ReturnValue', save_home, 'WardrobeCameraHome'); g.link(fov, 'FieldOfView', save_fov, 'WardrobeCameraFOV')
    g.link(location, 'ReturnValue', pose, 'Location'); g.link(rotation, 'ReturnValue', pose, 'Rotation')
    g.link(pose, 'ReturnValue', close, 'NewTransform'); g.link(camera, 'TopDownCamera', close, 'self')
    g.link(camera, 'TopDownCamera', zoom, 'self'); g.link(branch, 'True', save_home, 'execute')
    g.exec_chain(save_home, save_fov, close, zoom)
    fe = g.call(f'{GS}:GetActorOfClass', 2272, -128, ActorClass=cls_path(FRONT))
    valid = g.call(f'{KSL}:IsValid', 2272, 224); fe_ok = g.branch(2560, -128)
    hud = g.get('HUD', 2848, 224, class_path=cls_path(FRONT))
    valid_hud = g.call(f'{KSL}:IsValid', 3136, 224); hud_ok = g.branch(3136, -128)
    save_hud = g.set('WardrobeHUD', 3424, -128)
    visibility = g.call('/Script/UMG.Widget:GetVisibility', 3424, 224)
    save_visibility = g.set('WardrobeHUDVisibility', 3712, -128)
    hide = g.call('/Script/UMG.Widget:SetVisibility', 4000, -128, InVisibility='Hidden')
    g.exec_chain(zoom, fe, fe_ok); g.link(fe, 'ReturnValue', valid, 'Object'); g.link(valid, 'ReturnValue', fe_ok, 'Condition')
    g.link(fe, 'ReturnValue', hud, 'self'); g.link(hud, 'HUD', valid_hud, 'Object')
    g.link(valid_hud, 'ReturnValue', hud_ok, 'Condition'); g.link(fe_ok, 'True', hud_ok, 'execute')
    g.link(hud, 'HUD', save_hud, 'WardrobeHUD'); g.link(hud, 'HUD', visibility, 'self')
    g.link(visibility, 'ReturnValue', save_visibility, 'WardrobeHUDVisibility'); g.link(hud, 'HUD', hide, 'self')
    g.link(hud_ok, 'True', save_hud, 'execute'); g.exec_chain(save_hud, save_visibility, hide)
    original = g.get('WardrobeCameraHome', 544, 960); original_fov = g.get('WardrobeCameraFOV', 832, 960)
    restore = g.call(f'{SC}:K2_SetRelativeTransform', 1120, 736, bTeleport='true')
    restore_fov = g.call('/Script/Engine.CameraComponent:SetFieldOfView', 1408, 736)
    cached_hud = g.get('WardrobeHUD', 1696, 960); cached_visibility = g.get('WardrobeHUDVisibility', 2560, 960)
    cached_valid = g.call(f'{KSL}:IsValid', 1984, 960); restore_ok = g.branch(2272, 736)
    show = g.call('/Script/UMG.Widget:SetVisibility', 2848, 736)
    g.link(camera, 'TopDownCamera', restore, 'self'); g.link(original, 'WardrobeCameraHome', restore, 'NewTransform')
    g.link(camera, 'TopDownCamera', restore_fov, 'self'); g.link(original_fov, 'WardrobeCameraFOV', restore_fov, 'InFieldOfView')
    g.link(branch, 'False', restore, 'execute'); g.exec_chain(restore, restore_fov, restore_ok)
    g.link(cached_hud, 'WardrobeHUD', cached_valid, 'Object'); g.link(cached_valid, 'ReturnValue', restore_ok, 'Condition')
    g.link(restore_ok, 'True', show, 'execute'); g.link(cached_hud, 'WardrobeHUD', show, 'self')
    g.link(cached_visibility, 'WardrobeHUDVisibility', show, 'InVisibility')
    g.comment('Frame the wardrobe cinematic', '', [e, light, light_on, echo, branch, camera, home, fov, save_home, save_fov,
              location, rotation, pose, close, zoom, fe, valid, fe_ok, hud, valid_hud, hud_ok, save_hud,
              visibility, save_visibility, hide, original, original_fov, restore, restore_fov,
              cached_hud, cached_visibility, cached_valid, restore_ok, show], C_CAM)

    g, e = open_fn('WardrobeBodyBurst')
    pw = g.call(f'{GS}:GetPlayerCharacter', 32, 224, PlayerIndex=0)
    loc = g.call(f'{ACTOR}:K2_GetActorLocation', 288, 224)
    cap = g.get('CapsuleComponent', 32, 448, class_path='/Script/Engine.Character')
    half = g.call('/Script/Engine.CapsuleComponent:GetScaledCapsuleHalfHeight', 288, 448)
    g.link(pw, 'ReturnValue', loc, 'self'); g.link(pw, 'ReturnValue', cap, 'self')
    g.link(cap, 'CapsuleComponent', half, 'self')
    nodes, tail = [e, pw, loc, cap, half], e
    for i, (height, scale) in enumerate(((0.0, 1.1), (65.0, 0.8), (140.0, 0.5))):
        x = 576 + i * 864
        z = g.call(f'{KML}:Subtract_DoubleDouble', x, 576, A=height)
        offset = g.call(f'{KML}:MakeVector', x, 384)
        at = g.call(f'{KML}:Add_VectorVector', x + 288, 224)
        sand = g.call(f'{cls_path("/Game/FoA/VFX/Sand/BPL_SandFX")}:SpawnSandBurst', x + 576, 0, Scale=scale)
        g.link(half, 'ReturnValue', z, 'B'); g.link(z, 'ReturnValue', offset, 'Z')
        g.link(loc, 'ReturnValue', at, 'A'); g.link(offset, 'ReturnValue', at, 'B')
        g.link(at, 'ReturnValue', sand, 'Location'); g.exec_chain(tail, sand)
        nodes += [z, offset, at, sand]; tail = sand
    g.comment('Whole body sand scatter', '', nodes, C_VISUAL)

    g, e = open_fn('PlayerSand')
    assert HAS_PLAYER['SetSandOverlay'], 'BP_FoAPlayer.SetSandOverlay must exist before this build'
    pw = g.call(f'{GS}:GetPlayerPawn', 256, 192, PlayerIndex=0)
    cast = cast_to(g, 'BP_FoAPlayer', 544, 0)
    sand = g.call(f'{cls_path(PLAYER)}:SetSandOverlay', 864, 0)
    g.link(pw, 'ReturnValue', cast, 'Object'); g.exec_chain(e, cast)
    g.link(cast, 'then', sand, 'execute'); g.link(cast, 'AsBP_FoAPlayer', sand, 'self')
    g.link(e, 'Amount', sand, 'Amount')
    g.comment('Player sand skin', '', [e, pw, cast, sand], C_VISUAL)

    g, e = open_fn('BeginWardrobeTransition')
    active = g.get('bWardrobeTransition', 32, 192); rolling = g.get('bRollingOver', 32, 288)
    busy = g.call(f'{KML}:BooleanOR', 288, 192); br = g.branch(544, 0)
    on = g.set('bWardrobeTransition', 800, 0); g.default(on, 'bWardrobeTransition', 'true')
    now = g.call(f'{GS}:GetTimeSeconds', 800, 224); start = g.set('WardrobeTransitionStart', 1088, 0)
    cin = g.call(me('PlayerCinematic'), 1376, 0, Enable='true')
    pw, cm = wardrobe_pawn(g, 1376, 224)
    stop = g.call('/Script/Engine.CharacterMovementComponent:DisableMovement', 1664, 0)
    pc = g.call(f'{GS}:GetPlayerController', 1664, 384, PlayerIndex=0)
    lock = g.call(f'{CTRL}:SetIgnoreMoveInput', 1952, 0, bNewMoveInput='true')
    col = g.call(f'{ACTOR}:SetActorEnableCollision', 2240, 0, bNewActorEnableCollision='false')
    shot = g.call(me('SetWardrobeShot'), 2528, 0, Enable='true')
    top = g.call(me('EnterTopDown'), 2816, 0)
    g.link(active, 'bWardrobeTransition', busy, 'A'); g.link(rolling, 'bRollingOver', busy, 'B')
    g.link(busy, 'ReturnValue', br, 'Condition'); g.link(now, 'ReturnValue', start, 'WardrobeTransitionStart')
    g.link(cm, 'CharacterMovement', stop, 'self'); g.link(pc, 'ReturnValue', lock, 'self')
    g.link(pw, 'ReturnValue', col, 'self'); g.exec_chain(e, br); g.link(br, 'False', on, 'execute')
    g.exec_chain(on, start, cin, stop, lock, col, shot, top)
    nodes = [e, active, rolling, busy, br, on, now, start, cin, pw, cm, stop, pc, lock, col, shot, top]
    tail = top
    for i, (name, seconds) in enumerate(zip(TRANSITION_TIMERS, (0.05, VANISH_AT, REAPPEAR_AT, FINISH_AT))):
        tm = g.call(f'{KSL}:K2_SetTimer', 3200 + i * 320, 0, FunctionName=name,
                    Time=seconds, bLooping='true' if i == 0 else 'false')
        g.exec_chain(tail, tm); tail = tm; nodes.append(tm)
    g.comment('The wardrobe falls', '', nodes, C_CAM, padding=96)

    g, e = open_fn('WardrobeSandTick')
    active, br = wardrobe_active(g, e)
    now = g.call(f'{GS}:GetTimeSeconds', 544, 224); start = g.get('WardrobeTransitionStart', 544, 352)
    elapsed = g.call(f'{KML}:Subtract_DoubleDouble', 832, 224)
    out = g.call(f'{KML}:Divide_DoubleDouble', 1120, 224, B=VANISH_AT)
    remain = g.call(f'{KML}:Subtract_DoubleDouble', 1120, 448, A=FINISH_AT)
    inside = g.call(f'{KML}:Divide_DoubleDouble', 1408, 448, B=FINISH_AT - REAPPEAR_AT)
    clamp_out = g.call(f'{KML}:FClamp', 1408, 224, Min=0.0, Max=1.0)
    clamp_in = g.call(f'{KML}:FClamp', 1696, 448, Min=0.0, Max=1.0)
    idle = g.call(f'{KML}:Lerp', 1984, 448, A=0.25, B=1.0)
    early = g.call(f'{KML}:Less_DoubleDouble', 1696, 224, B=REAPPEAR_AT)
    choose = g.call(f'{KML}:SelectFloat', 2272, 224)
    apply = g.call(me('PlayerSand'), 2560, 0)
    g.link(now, 'ReturnValue', elapsed, 'A'); g.link(start, 'WardrobeTransitionStart', elapsed, 'B')
    g.link(elapsed, 'ReturnValue', out, 'A'); g.link(elapsed, 'ReturnValue', remain, 'B')
    g.link(remain, 'ReturnValue', inside, 'A'); g.link(out, 'ReturnValue', clamp_out, 'Value')
    g.link(inside, 'ReturnValue', clamp_in, 'Value'); g.link(clamp_in, 'ReturnValue', idle, 'Alpha')
    g.link(elapsed, 'ReturnValue', early, 'A'); g.link(early, 'ReturnValue', choose, 'bPickA')
    g.link(clamp_out, 'ReturnValue', choose, 'A'); g.link(idle, 'ReturnValue', choose, 'B')
    g.link(choose, 'ReturnValue', apply, 'Amount'); g.link(br, 'True', apply, 'execute')
    g.comment('Sand unravels and reforms', '', [e, active, br, now, start, elapsed, out, remain, inside,
              clamp_out, clamp_in, idle, early, choose, apply], C_VISUAL)

    g, e = open_fn('SetDoorHidden')
    nodes, tail = [e], e
    visible = g.call(f'{KML}:Not_PreBool', 32, 192); g.link(e, 'Hidden', visible, 'A'); nodes.append(visible)
    for i, var in enumerate(('Door', 'DoorFrame')):
        ref = g.get(var, 256 + i * 960, 224)
        hide = g.call(f'{ACTOR}:SetActorHiddenInGame', 544 + i * 960, 0)
        col = g.call(f'{ACTOR}:SetActorEnableCollision', 832 + i * 960, 0)
        g.link(ref, var, hide, 'self'); g.link(ref, var, col, 'self')
        g.link(e, 'Hidden', hide, 'bNewHidden'); g.link(visible, 'ReturnValue', col, 'bNewActorEnableCollision')
        g.exec_chain(tail, hide, col); tail = col; nodes += [ref, hide, col]
    g.comment('Door vanishes between walls', '', nodes, C_CAM)

    g, e = open_fn('WardrobeVanish')
    active, br = wardrobe_active(g, e); pw, cm = wardrobe_pawn(g)
    hide = g.call(f'{ACTOR}:SetActorHiddenInGame', 1120, 0, bNewHidden='true')
    g.link(pw, 'ReturnValue', hide, 'self'); g.link(br, 'True', hide, 'execute')
    sand = g.call(me('WardrobeBodyBurst'), 1408, 0)
    door = g.call(me('SetDoorHidden'), 1696, 0, Hidden='true')
    wall = g.call(me('SetOldWall'), 2016, 0, Enable='true')
    g.exec_chain(hide, sand, door, wall)
    g.comment('The impact scatters him', '', [e, active, br, pw, cm, hide, sand, door, wall], C_VISUAL)

    g, e = open_fn('SetWardrobeBlockers')
    enable = g.branch(256, 0); g.link(e, 'Enable', enable, 'Condition'); g.exec_chain(e, enable)
    wardrobe = g.get('Wardrobe', 256, 224)
    bounds = g.call(f'{ACTOR}:GetActorBounds', 544, 224, bOnlyCollidingComponents='false')
    origin = g.call(f'{KML}:BreakVector', 832, 224); extent = g.call(f'{KML}:BreakVector', 832, 448)
    center = g.call(f'{KML}:MakeVector', 1120, 224, Z=150.0)
    ex = g.call(f'{KML}:Add_DoubleDouble', 1120, 448, B=8.0)
    ey = g.call(f'{KML}:Add_DoubleDouble', 1120, 640, B=8.0)
    size = g.call(f'{KML}:MakeVector', 1408, 448, Z=150.0)
    floorbox = g.get('FallenWardrobeBlocker', 1408, 224)
    move = g.call(f'{SC}:K2_SetWorldLocation', 1696, 0)
    resize = g.call('/Script/Engine.BoxComponent:SetBoxExtent', 1984, 0, bUpdateOverlaps='false')
    oldbox = g.get('OldDoorBlocker', 1984, 448); home = g.get('FrameHome', 1696, 800)
    parts = g.call(f'{KML}:BreakTransform', 1984, 800)
    offset = g.call(f'{KML}:MakeVector', 2272, 640, Z=150.0)
    raised = g.call(f'{KML}:Add_VectorVector', 2272, 448)
    oldmove = g.call(f'{SC}:K2_SetWorldLocation', 2560, 0)
    oldrot = g.call(f'{SC}:K2_SetWorldRotation', 2848, 0)
    g.link(wardrobe, 'Wardrobe', bounds, 'self'); g.link(bounds, 'Origin', origin, 'InVec')
    g.link(bounds, 'BoxExtent', extent, 'InVec'); g.link(origin, 'X', center, 'X'); g.link(origin, 'Y', center, 'Y')
    g.link(extent, 'X', ex, 'A'); g.link(extent, 'Y', ey, 'A'); g.link(ex, 'ReturnValue', size, 'X')
    g.link(ey, 'ReturnValue', size, 'Y'); g.link(floorbox, 'FallenWardrobeBlocker', move, 'self')
    g.link(center, 'ReturnValue', move, 'NewLocation'); g.link(floorbox, 'FallenWardrobeBlocker', resize, 'self')
    g.link(size, 'ReturnValue', resize, 'InBoxExtent'); g.link(home, 'FrameHome', parts, 'InTransform')
    g.link(parts, 'Location', raised, 'A'); g.link(offset, 'ReturnValue', raised, 'B')
    g.link(raised, 'ReturnValue', oldmove, 'NewLocation')
    g.link(oldbox, 'OldDoorBlocker', oldmove, 'self'); g.link(oldbox, 'OldDoorBlocker', oldrot, 'self')
    g.link(parts, 'Rotation', oldrot, 'NewRotation'); g.link(enable, 'True', move, 'execute')
    g.exec_chain(move, resize, oldmove, oldrot)
    nodes, tail = [e, enable, wardrobe, bounds, origin, extent, center, ex, ey, size, floorbox, move,
                   resize, oldbox, home, parts, offset, raised, oldmove, oldrot], oldrot
    for i, var in enumerate(('FallenWardrobeBlocker', 'OldDoorBlocker')):
        ref = g.get(var, 3200 + i * 960, 224)
        br = g.branch(3200 + i * 960, 0)
        on = g.call('/Script/Engine.PrimitiveComponent:SetCollisionEnabled', 3488 + i * 960, -128, NewType='QueryOnly')
        off = g.call('/Script/Engine.PrimitiveComponent:SetCollisionEnabled', 3488 + i * 960, 128, NewType='NoCollision')
        g.link(e, 'Enable', br, 'Condition'); g.link(ref, var, on, 'self'); g.link(ref, var, off, 'self')
        if i == 0:
            g.link(enable, 'False', br, 'execute'); g.exec_chain(tail, br)
        else:
            g.exec_chain(tail[0], br); g.exec_chain(tail[1], br)
        g.link(br, 'True', on, 'execute'); g.link(br, 'False', off, 'execute')
        tail = (on, off); nodes += [ref, br, on, off]
    g.comment('Fallen area stays blocked', '', nodes, C_CAM)

    g, e = open_fn('WardrobeReappear')
    active, br = wardrobe_active(g, e); pw, cm = wardrobe_pawn(g)
    block = g.call(me('SetWardrobeBlockers'), 1120, 0, Enable='true')
    col = g.call(f'{ACTOR}:SetActorEnableCollision', 1408, 0, bNewActorEnableCollision='true')
    wardrobe = g.get('Wardrobe', 1120, 288)
    bounds = g.call(f'{ACTOR}:GetActorBounds', 1408, 288, bOnlyCollidingComponents='false')
    origin = g.call(f'{KML}:BreakVector', 1696, 224); extent = g.call(f'{KML}:BreakVector', 1696, 448)
    cap = g.get('CapsuleComponent', 1120, 640, class_path='/Script/Engine.Character')
    radius = g.call('/Script/Engine.CapsuleComponent:GetScaledCapsuleRadius', 1408, 640)
    half = g.call('/Script/Engine.CapsuleComponent:GetScaledCapsuleHalfHeight', 1408, 800)
    left = g.call(f'{KML}:Subtract_DoubleDouble', 1984, 224)
    clear = g.call(f'{KML}:Add_DoubleDouble', 1984, 448, B=24.0)
    x = g.call(f'{KML}:Subtract_DoubleDouble', 2272, 224)
    z = g.call(f'{KML}:Add_DoubleDouble', 2272, 448, B=2.0)
    dest = g.call(f'{KML}:MakeVector', 2560, 224)
    tp = g.call(f'{ACTOR}:K2_TeleportTo', 2848, 0, DestRotation='(Pitch=0,Yaw=-90,Roll=0)')
    success = g.branch(3168, 0); fallback = g.call(me('ReturnToBed'), 3456, 160)
    show = g.call(f'{ACTOR}:SetActorHiddenInGame', 3744, 0, bNewHidden='false')
    g.link(br, 'True', block, 'execute'); g.exec_chain(block, col, tp, success)
    g.link(pw, 'ReturnValue', col, 'self'); g.link(pw, 'ReturnValue', cap, 'self')
    g.link(wardrobe, 'Wardrobe', bounds, 'self'); g.link(bounds, 'Origin', origin, 'InVec')
    g.link(bounds, 'BoxExtent', extent, 'InVec'); g.link(cap, 'CapsuleComponent', radius, 'self')
    g.link(cap, 'CapsuleComponent', half, 'self'); g.link(origin, 'X', left, 'A'); g.link(extent, 'X', left, 'B')
    g.link(radius, 'ReturnValue', clear, 'A'); g.link(left, 'ReturnValue', x, 'A'); g.link(clear, 'ReturnValue', x, 'B')
    g.link(half, 'ReturnValue', z, 'A'); g.link(x, 'ReturnValue', dest, 'X')
    g.link(origin, 'Y', dest, 'Y'); g.link(z, 'ReturnValue', dest, 'Z')
    g.link(dest, 'ReturnValue', tp, 'DestLocation'); g.link(pw, 'ReturnValue', tp, 'self')
    g.link(tp, 'ReturnValue', success, 'Condition'); g.link(success, 'False', fallback, 'execute')
    g.link(success, 'True', show, 'execute'); g.exec_chain(fallback, show); g.link(pw, 'ReturnValue', show, 'self')
    sand = g.call(me('WardrobeBodyBurst'), 4032, 0); g.exec_chain(show, sand)
    g.comment('Reform behind the wardrobe', '', [e, active, br, pw, cm, block, col, wardrobe, bounds, origin, extent,
              cap, radius, half, left, clear, x, z, dest, tp, success, fallback, show, sand], C_CAM)

    g, e = open_fn('FinishWardrobeTransition')
    nodes, tail = [e], e
    for i, name in enumerate(TRANSITION_TIMERS):
        clear = g.call(f'{KSL}:K2_ClearTimer', 256 + i * 320, 0, FunctionName=name)
        g.exec_chain(tail, clear); tail = clear; nodes.append(clear)
    active = g.get('bWardrobeTransition', 1536, 224); br = g.branch(1536, 0)
    off = g.set('bWardrobeTransition', 1824, 0)
    shot = g.call(me('SetWardrobeShot'), 2112, -192, Enable='false')
    pw, cm = wardrobe_pawn(g, 1824, 224)
    show = g.call(f'{ACTOR}:SetActorHiddenInGame', 2112, 0, bNewHidden='false')
    col = g.call(f'{ACTOR}:SetActorEnableCollision', 2400, 0, bNewActorEnableCollision='true')
    move = g.call('/Script/Engine.CharacterMovementComponent:SetMovementMode', 2688, 0, NewMovementMode='MOVE_Walking')
