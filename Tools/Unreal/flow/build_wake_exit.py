"""Release the wake-up capsule outside the real bedding collision; both film completion and skip share this hook."""


def build_wake_exit():
    # shortcut: this bedroom's bed exits toward +Y; use an exit marker if its orientation changes.
    g, e = open_fn('SafeWakeExit')
    bed = g.get('WakeBed', 32, 224)
    valid = g.call(f'{KSL}:IsValid', 256, 224); exists = g.branch(544, 0)
    g.link(bed, 'WakeBed', valid, 'Object'); g.link(valid, 'ReturnValue', exists, 'Condition'); g.exec_chain(e, exists)
    bounds = g.call(f'{ACTOR}:GetActorBounds', 544, 224, bOnlyCollidingComponents='false')
    origin = g.call(f'{KML}:BreakVector', 832, 224); extent = g.call(f'{KML}:BreakVector', 832, 448)
    pw = g.call(f'{GS}:GetPlayerCharacter', 32, 640, PlayerIndex=0)
    cap = g.get('CapsuleComponent', 288, 640, class_path='/Script/Engine.Character')
    radius = g.call('/Script/Engine.CapsuleComponent:GetScaledCapsuleRadius', 544, 640)
    half = g.call('/Script/Engine.CapsuleComponent:GetScaledCapsuleHalfHeight', 544, 800)
    loc = g.call(f'{ACTOR}:K2_GetActorLocation', 832, 640)
    current = g.call(f'{KML}:BreakVector', 1120, 640)
    front = g.call(f'{KML}:Add_DoubleDouble', 1120, 224)
    clearance = g.call(f'{KML}:Add_DoubleDouble', 1120, 448, B=12.0)
    safe_y = g.call(f'{KML}:Add_DoubleDouble', 1408, 224)
    delta_x = g.call(f'{KML}:Subtract_DoubleDouble', 1408, 640)
    distance_x = g.call(f'{KML}:Abs', 1696, 640)
    width = g.call(f'{KML}:Add_DoubleDouble', 1408, 448)
    in_x = g.call(f'{KML}:LessEqual_DoubleDouble', 1984, 448)
    in_y = g.call(f'{KML}:Less_DoubleDouble', 1984, 224)
    overlap = g.call(f'{KML}:BooleanAND', 2272, 224); embedded = g.branch(2560, 0)
    z = g.call(f'{KML}:Add_DoubleDouble', 2272, 640, B=2.15)
    destination = g.call(f'{KML}:MakeVector', 2560, 448)
    facing = g.call(f'{ACTOR}:K2_GetActorRotation', 2560, 640)
    teleport = g.call(f'{ACTOR}:K2_TeleportTo', 2848, 0)
    success = g.branch(3168, 0); fallback = g.call(me('ReturnToBed'), 3456, 0)
    g.link(bed, 'WakeBed', bounds, 'self'); g.link(bounds, 'Origin', origin, 'InVec')
    g.link(bounds, 'BoxExtent', extent, 'InVec'); g.link(pw, 'ReturnValue', cap, 'self')
    g.link(cap, 'CapsuleComponent', radius, 'self'); g.link(cap, 'CapsuleComponent', half, 'self')
    g.link(pw, 'ReturnValue', loc, 'self'); g.link(loc, 'ReturnValue', current, 'InVec')
    g.link(origin, 'Y', front, 'A'); g.link(extent, 'Y', front, 'B')
    g.link(radius, 'ReturnValue', clearance, 'A'); g.link(front, 'ReturnValue', safe_y, 'A')
    g.link(clearance, 'ReturnValue', safe_y, 'B'); g.link(current, 'X', delta_x, 'A')
    g.link(origin, 'X', delta_x, 'B'); g.link(delta_x, 'ReturnValue', distance_x, 'A')
    g.link(extent, 'X', width, 'A'); g.link(radius, 'ReturnValue', width, 'B')
    g.link(distance_x, 'ReturnValue', in_x, 'A'); g.link(width, 'ReturnValue', in_x, 'B')
    g.link(current, 'Y', in_y, 'A'); g.link(safe_y, 'ReturnValue', in_y, 'B')
    g.link(in_x, 'ReturnValue', overlap, 'A'); g.link(in_y, 'ReturnValue', overlap, 'B')
    g.link(overlap, 'ReturnValue', embedded, 'Condition'); g.link(exists, 'True', embedded, 'execute')
    g.link(half, 'ReturnValue', z, 'A'); g.link(origin, 'X', destination, 'X')
    g.link(safe_y, 'ReturnValue', destination, 'Y'); g.link(z, 'ReturnValue', destination, 'Z')
    g.link(pw, 'ReturnValue', facing, 'self'); g.link(pw, 'ReturnValue', teleport, 'self')
    g.link(destination, 'ReturnValue', teleport, 'DestLocation'); g.link(facing, 'ReturnValue', teleport, 'DestRotation')
    g.link(embedded, 'True', teleport, 'execute'); g.exec_chain(teleport, success)
    g.link(teleport, 'ReturnValue', success, 'Condition'); g.link(success, 'False', fallback, 'execute')
    g.link(exists, 'False', fallback, 'execute')
    g.comment('Stand clear of the bedding', '', [e, bed, valid, exists, bounds, origin, extent, pw, cap, radius,
              half, loc, current, front, clearance, safe_y, delta_x, distance_x, width, in_x, in_y, overlap,
              embedded, z, destination, facing, teleport, success, fallback], C_FLOW)
